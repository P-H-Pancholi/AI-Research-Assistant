package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"strings"
	"time"
)

type AskRequest struct {
	Prompt string `json:"prompt"`
}

type AskResponse struct {
	Response string `json:"response,omitempty"`
	Error    string `json:"error,omitempty"`
	Tokens   string `json:"tokens"`
}

type ChatMessage struct {
	Role    string `json:"role"`
	Content string `json:"content"`
}

type ChatCompletionRequest struct {
	Model    string        `json:"model"`
	Messages []ChatMessage `json:"messages"`
	Tokens   int           `json:"n"`
}

type ChatCompletionResponse struct {
	Choices []struct {
		Message struct {
			Content string `json:"content"`
		} `json:"message"`
	} `json:"choices"`

	Error *struct {
		Message string `json:"message"`
	} `json:"error,omitempty"`
}

func askHandler(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/json")

	if r.Method != "POST" {
		w.WriteHeader(http.StatusMethodNotAllowed)
		json.NewEncoder(w).Encode(AskResponse{Error: "Only Post request is allowed"})
		return
	}

	var req AskRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil || strings.TrimSpace(req.Prompt) == "" {
		w.WriteHeader(http.StatusBadRequest)
		json.NewEncoder(w).Encode(AskResponse{Error: "Empty prompt not allowed"})
		return
	}

	baseUrl := os.Getenv("RESEARCH_LLM_URL")
	// http://model-runner.docker.internal/v1/
	modelName := os.Getenv("RESEARCH_LLM_MODEL")
	// ai/qwen2.5

	llmEndpoint := strings.TrimRight(baseUrl, "/")
	if !strings.HasSuffix(llmEndpoint, "/chat/completions") {
		llmEndpoint = fmt.Sprintf("%s/chat/completions", llmEndpoint)
	}

	llmReqPayload := ChatCompletionRequest{
		Model: modelName,
		Messages: []ChatMessage{
			{Role: "user", Content: req.Prompt},
		},
		Tokens: 3,
	}

	// send request to model

	payloadBytes, err := json.Marshal(llmReqPayload)
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		json.NewEncoder(w).Encode(AskResponse{Error: "Failed to marshal LLM request"})
		return
	}

	client := http.Client{
		Timeout: 120 * time.Second,
	}
	httpReq, err := http.NewRequestWithContext(r.Context(), http.MethodPost, llmEndpoint, bytes.NewBuffer(payloadBytes))
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		json.NewEncoder(w).Encode(AskResponse{Error: "Failed to create LLM request"})
		return
	}
	httpReq.Header.Set("Content-Type", "application/json")
	resp, err := client.Do(httpReq)
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		json.NewEncoder(w).Encode(AskResponse{Error: "Fail to send request to LLM"})
		return
	}
	defer resp.Body.Close()

	bodyBytes, err := io.ReadAll(resp.Body)
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		json.NewEncoder(w).Encode(AskResponse{Error: "Fail to parse response body"})
		return
	}
	fmt.Printf("Raw LLM Response: %s\n", string(bodyBytes))

	var llmResp ChatCompletionResponse
	if err := json.Unmarshal(bodyBytes, &llmResp); err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		json.NewEncoder(w).Encode(AskResponse{Error: "Invalid JSON response from model runner"})
		return
	}

	if llmResp.Error != nil && llmResp.Error.Message != "" {
		w.WriteHeader(http.StatusInternalServerError)
		json.NewEncoder(w).Encode(AskResponse{Error: llmResp.Error.Message})
		return
	}

	if len(llmResp.Choices) == 0 {
		w.WriteHeader(http.StatusInternalServerError)
		json.NewEncoder(w).Encode(AskResponse{Error: "No response text generated by model"})
		return
	}
	fmt.Println(len(llmResp.Choices))

	// 6. Return response to user
	w.WriteHeader(http.StatusOK)
	json.NewEncoder(w).Encode(AskResponse{
		Response: llmResp.Choices[0].Message.Content,
	})
}
func main() {
	http.HandleFunc("/api/ask", askHandler)
	if err := http.ListenAndServe(":8080", nil); err != nil {
		log.Fatalf("Server shutdown: %v", err)
	}
}
